const _HIGHER_PR_PATTERN = /^Higher review priority estimate because the changed provision concerns (.+)\. This is not a legal impact assessment\.$/i;
const _MEDIUM_PR_PATTERN  = /^Medium review priority because the changed text concerns (.+)\. This is not a legal impact assessment\.$/i;

function _translateConcernList(concernsText, lang) {
  return concernsText.split(',').map(raw => {
    const key = raw.trim();
    return (_DYNAMIC_CONCERNS[key] && _DYNAMIC_CONCERNS[key][lang]) ? _DYNAMIC_CONCERNS[key][lang] : key;
  }).join(', ');
}

/**
 * Translate a backend-generated dynamic string (title, summary, priority_reason)
 * into the current UI language. Leaves the text unchanged when no translation is
 * available, ensuring evidence text and numbers are never altered.
 */
function tDynamic(text) {
  if (!text || currentLang === 'en') return text;
  const lang = currentLang;

  // 1. Exact dictionary match
  const exact = DYNAMIC_TRANSLATIONS[text];
  if (exact && exact[lang]) return exact[lang];

  // 2. Dynamic "Higher review priority…" pattern
  let m = text.match(_HIGHER_PR_PATTERN);
  if (m && _HIGHER_PRIORITY_TEMPLATES[lang]) {
    const concerns = _translateConcernList(m[1], lang);
    return _HIGHER_PRIORITY_TEMPLATES[lang].replace('{0}', concerns);
  }

  // 3. Dynamic "Medium review priority…" pattern
  m = text.match(_MEDIUM_PR_PATTERN);
  if (m && _MEDIUM_PRIORITY_TEMPLATES[lang]) {
    const catKey = m[1].trim().toLowerCase();
    const catTr = (_DYNAMIC_CATEGORIES[catKey] && _DYNAMIC_CATEGORIES[catKey][lang]) ? _DYNAMIC_CATEGORIES[catKey][lang] : m[1].trim();
    return _MEDIUM_PRIORITY_TEMPLATES[lang].replace('{0}', catTr);
  }

  return text; // fallback: original
}

function t(key, params = {}) {
  const entry = TRANSLATIONS[key];
  let text = (entry && entry[currentLang]) ? entry[currentLang] : (entry && entry.en) ? entry.en : key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
  }
  return text;
}

function tCategory(cat) {
  if (!cat) return t('cat.other');
  const lower = cat.toLowerCase();
  if (lower.includes('repay') || lower.includes('recovery')) return t('cat.repayment');
  if (lower.includes('financ') || lower.includes('loan') || lower.includes('credit')) return t('cat.financial_assistance');
  if (lower.includes('eligib') || lower.includes('qualif')) return t('cat.eligibility');
  if (lower.includes('application') || lower.includes('apply')) return t('cat.application_process');
  if (lower.includes('document') || lower.includes('proof')) return t('cat.required_documents');
  if (lower.includes('implement')) return t('cat.implementation');
  if (lower.includes('deadline') || lower.includes('due')) return t('cat.deadlines');
  if (lower.includes('responsib') || lower.includes('ministry')) return t('cat.responsibilities');
  if (lower.includes('monitor') || lower.includes('audit')) return t('cat.monitoring');
  return t('cat.other');
}

function tPriority(pri) {
  const norm = (pri || 'Low').toLowerCase();
  if (norm === 'high') return t('priority.high');
  if (norm === 'medium') return t('priority.medium');
  return t('priority.low');
}

function tPriorityShort(pri) {
  const norm = (pri || 'Low').toLowerCase();
  if (norm === 'high') return currentLang === 'en' ? 'High' : t('priority.high');
  if (norm === 'medium') return currentLang === 'en' ? 'Medium' : t('priority.medium');
  return currentLang === 'en' ? 'Low' : t('priority.low');
}

function tAudience(aud) {
  if (aud === 'Businesses') return t('filter.businesses');
  if (aud === 'Students') return t('filter.students');
  if (aud === 'General Citizens') return t('filter.citizens');
  if (aud === 'ALL') return t('filter.all_audiences');
  return aud;
}

function setLanguage(lang) {
  if (!LANGUAGES[lang]) lang = 'en';
  currentLang = lang;
  try {
    localStorage.setItem('civiclens_language', lang);
  } catch (e) {
    // Ignore storage errors in sandbox
  }
  document.documentElement.lang = lang;
  document.documentElement.dir = LANGUAGES[lang].dir;

  // Apply static DOM translations
  updateDOMTranslations();

  // Notify any listeners (e.g. app.js re-render)
  window.dispatchEvent(new CustomEvent('civiclens:languagechange', { detail: { lang } }));
}

function updateDOMTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (key) {
      el.textContent = t(key);
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (key) {
      el.placeholder = t(key);
    }
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.dataset.i18nTitle;
    if (key) {
      el.title = t(key);
    }
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.dataset.i18nAria;
    if (key) {
      el.setAttribute('aria-label', t(key));
    }
  });

  const langSelect = document.querySelector('#lang-select');
  if (langSelect && langSelect.value !== currentLang) {
    langSelect.value = currentLang;
  }
}

// Initialise language on load
function initI18n() {
  let saved = 'en';
  try {
    saved = localStorage.getItem('civiclens_language') || 'en';
  } catch (e) {}
  if (!LANGUAGES[saved]) saved = 'en';
  setLanguage(saved);
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
