def _translate_concern_list(concerns_text: str, target: str) -> str:
    """Translate a comma-joined list of concern phrases in a priority_reason string."""
    parts = [p.strip() for p in concerns_text.split(",")]
    translated = [CONCERN_PHRASES.get(p, {}).get(target, p) for p in parts]
    return ", ".join(translated)


def _translate_priority_reason(text: str, target: str) -> str | None:
    """Try to translate a dynamic priority_reason. Returns None if no pattern matched."""
    trimmed = text.strip()

    m = _HIGHER_PRIORITY_RE.match(trimmed)
    if m:
        concerns = _translate_concern_list(m.group(1), target)
        template = HIGHER_PRIORITY_TEMPLATES.get(target)
        if template:
            return template.format(concerns)

    m = _MEDIUM_PRIORITY_RE.match(trimmed)
    if m:
        category_en = m.group(1).strip()
        cat_tr = CATEGORY_TERMS.get(category_en.lower(), {}).get(target, category_en)
        template = MEDIUM_PRIORITY_TEMPLATES.get(target)
        if template:
            return template.format(cat_tr)

    return None


def translate_policy_text(text: str, target_lang: str) -> str:
    """Translate policy text into target language while strictly preserving numbers and citations.
    
    If text is empty, in English, or target_lang is English, returns text as-is.
    """
    if not text or not isinstance(text, str):
        return text
    if not target_lang or target_lang.lower() == "en" or target_lang.lower() not in SUPPORTED_LANGUAGES:
        return text

    target = target_lang.lower()
    trimmed = text.strip()

    # Exact dictionary match
    if trimmed in POLICY_PHRASE_TRANSLATIONS:
        translated = POLICY_PHRASE_TRANSLATIONS[trimmed].get(target)
        if translated:
            return translated

    # Pattern-based slot translation
    for pattern, templates in PATTERN_REPLACEMENTS:
        m = pattern.match(trimmed)
        if m and target in templates:
            groups = m.groups()
            template = templates[target]
            return template.format(*groups)

    # If the text is a composite sentence, check if components match
    parts = trimmed.split(". ")
    if len(parts) > 1:
        translated_parts = []
        all_matched = True
        for part in parts:
            p_strip = part.strip()
            if not p_strip.endswith("."):
                p_with_dot = p_strip + "."
            else:
                p_with_dot = p_strip
            if p_with_dot in POLICY_PHRASE_TRANSLATIONS and target in POLICY_PHRASE_TRANSLATIONS[p_with_dot]:
                translated_parts.append(POLICY_PHRASE_TRANSLATIONS[p_with_dot][target])
            else:
                all_matched = False
                break
        if all_matched:
            return " ".join(translated_parts)

    # Pattern-based priority_reason translation
    pr_translated = _translate_priority_reason(trimmed, target)
    if pr_translated:
        return pr_translated

    return text


def translate_analysis_dict(analysis: dict[str, Any], target_lang: str) -> dict[str, Any]:
    """Translate AI analysis fields to the target language without altering evidence or validation.
    
    Strictly preserves:
    - Evidence IDs, supporting_evidence, impact_supporting_evidence
    - Change types, categories, importance classifications, confidence numbers
    - Automated claim validation statuses (which evaluate source grounding)
    """
    if not analysis or not isinstance(analysis, dict) or target_lang.lower() == "en":
        return analysis

    target = target_lang.lower()
    translated = copy.deepcopy(analysis)

    # Translate top-level summary
    if "summary" in translated and isinstance(translated["summary"], str):
        translated["summary"] = translate_policy_text(translated["summary"], target)

    # Translate individual groups
    if "groups" in translated and isinstance(translated["groups"], list):
        for group in translated["groups"]:
            if not isinstance(group, dict):
                continue
            for field in (
                "title", "change_summary", "what_changed", "previous_rule",
                "updated_rule", "why_it_matters", "who_may_be_affected",
                "simple_explanation", "unknown_information", "limitations",
                "priority_reason",
            ):
                if field in group and isinstance(group[field], str):
                    group[field] = translate_policy_text(group[field], target)

            for list_field in ("potentially_affected_groups", "practical_implications", "what_changed_for_them"):
                if list_field in group and isinstance(group[list_field], list):
                    group[list_field] = [
                        translate_policy_text(item, target) if isinstance(item, str) else item
                        for item in group[list_field]
                    ]

    return translated
